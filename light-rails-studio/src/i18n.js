export function tr(lang, key) {
  return UI[lang]?.[key] ?? UI.en[key] ?? key
}
export function patternName(lang, name) {
  return lang === 'zh' ? (PATTERN_ZH[name] || name) : name
}
export function paramLabel(lang, label) {
  if (lang !== 'zh') return label
  const clean = label.trim()
  if (PARAM_ZH[clean]) return PARAM_ZH[clean]
  if (/^[ph]\d[xy]$/.test(clean)) return clean.toUpperCase()
  return clean
}
